import json, subprocess, os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
from howto_src import ROLES, THEMES, VIDEOS, FAQ
OUT = os.environ.get("OUT", os.path.join(HERE, "out"))
def dur(v):
    f = f"{OUT}/{v}.mp4"
    if not os.path.exists(f): return 0
    return round(float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f], capture_output=True, text=True).stdout.strip()), 1)
vids = [dict(id=i, roles=r, layout=l, title=t, steps=s, dur=dur(i)) for i, r, l, t, s in VIDEOS]
vid_ids = {v["id"] for v in vids}
faq = []
for i, th, roles, q, a, v in FAQ:
    assert v is None or v in vid_ids, ("missing video", v)
    assert th in dict(THEMES), th
    faq.append(dict(id=i, theme=th, roles=roles, q=q, a=a, video=v))
ids = [f["id"] for f in faq]; assert len(ids) == len(set(ids)), "duplicate ids"
data = dict(roles=ROLES, themes=[dict(id=a, label=b) for a, b in THEMES], videos=vids, faq=faq)
txt = json.dumps(data, ensure_ascii=False, indent=1)
bad = [c for c in "—–" if c in txt]
assert not bad, "dash found"
js = "/* How to section data: user types, themes, videos and common questions. Generated by tools/howto-videos/build_howto.py from howto_src.py; edit questions there. */\nwindow.HOWTO = " + txt + ";\n"
open(os.path.join(REPO, "site", "guide", "howto-data.js"), "w").write(js)
missing = [v["id"] for v in vids if not v["dur"]]
print(f"{len(vids)} videos ({len(missing)} not recorded: {missing}), {len(faq)} questions, {sum(1 for f in faq if f['video'])} with video")
unused = vid_ids - {f["video"] for f in faq}
print("videos without a question:", sorted(unused))
